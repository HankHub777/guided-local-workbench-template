#!/usr/bin/env python3
"""Build a single-file context bundle for handing to an LLM chatbot.

Concatenates the template's canonical orientation files into one Markdown
file so a non-technical user can upload/paste one document instead of
several, at the start of a chatbot session. See README.md's
"LLM chatbot 工作方式" section for how it's used.

Usage:
    python scripts/build_context_bundle.py [--output PATH]

Stdlib only — no install step required.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from datetime import datetime
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Canonical orientation files an LLM chatbot needs before it can safely
# reason about this project. Deliberately excludes task-specific files
# (a `shared/` contract, code, data) — those get attached separately, only
# when the task actually needs them. Keep in rough reading order: rules,
# boundary, index, product intent, architecture.
BUNDLE_FILES = [
    "AGENTS.md",
    "docs/TEMPLATE_BOUNDARY.md",
    "docs/FILE_MANIFEST.md",
    "ai/PROJECT_CONTEXT.md",
    "ai/ARCHITECTURE_RULES.md",
]

DEFAULT_OUTPUT = PROJECT_ROOT / "LLM_CONTEXT_BUNDLE.md"

PREAMBLE = """# LLM Context Bundle

Generated: {timestamp}
Source commit: {commit}
Generated by `scripts/build_context_bundle.py` — do not hand-edit this file; edit the source files listed below and regenerate.

This bundle contains the template's canonical orientation files, not the whole project. If this task needs a specific `shared/` contract, data file, or code file, ask the user for it separately.

Included files: {file_list}
"""


def get_source_commit() -> str:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            timeout=5,
            check=True,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown (git not available)"
    commit = result.stdout.strip()
    if not commit:
        return "unknown"
    dirty = subprocess.run(
        ["git", "status", "--porcelain"],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
        timeout=5,
    )
    if dirty.returncode == 0 and dirty.stdout.strip():
        return f"{commit} (plus uncommitted changes)"
    return commit


def build_bundle() -> str:
    missing = [path for path in BUNDLE_FILES if not (PROJECT_ROOT / path).is_file()]
    if missing:
        raise FileNotFoundError(
            "missing canonical source file(s), refusing to produce a partial bundle: "
            + ", ".join(missing)
        )

    sections = [
        PREAMBLE.format(
            timestamp=datetime.now().isoformat(timespec="seconds"),
            commit=get_source_commit(),
            file_list=", ".join(f"`{path}`" for path in BUNDLE_FILES),
        )
    ]
    for path in BUNDLE_FILES:
        content = (PROJECT_ROOT / path).read_text(encoding="utf-8")
        sections.append(f"---\n## FILE: {path}\n---\n\n{content.rstrip()}\n")

    return "\n".join(sections)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    try:
        bundle = build_bundle()
    except FileNotFoundError as exc:
        print(f"error: {exc}")
        return 1

    args.output.write_text(bundle, encoding="utf-8")
    size_kb = args.output.stat().st_size / 1024
    try:
        display_path = args.output.resolve().relative_to(PROJECT_ROOT)
    except ValueError:
        display_path = args.output
    print(f"Wrote {display_path} ({size_kb:.1f} KB)")
    print("Upload or paste this single file to your chatbot at the start of a session.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
